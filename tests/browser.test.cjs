  await ev('document.querySelector("#build").click()'); await sleep(750);
  assert.equal(await ev('document.querySelectorAll("[data-part=material],[data-part=satellite]").length'), 0);
  assert.equal(await ev('document.querySelector(\'[data-part="engine"][data-index="1"]\').disabled'), true);
  assert.equal(await ev('document.querySelector(\'[data-part="boosters"][data-index="2"]\').disabled'), true);
  assert.equal(await ev('document.querySelector(\'[data-part="instruments"][data-index="1"]\').disabled'), true);
