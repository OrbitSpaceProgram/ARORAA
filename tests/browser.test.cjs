  await ev(`flightController?.destroy();flightController=null;localStorage.removeItem(SAVE_KEY);localStorage.setItem('orbit-foundry-campaign-v2',JSON.stringify({version:2,credits:4200,status:'active',sequence:1,days:18,records:[{id:1,success:true,planet:'Mercury',cost:1000,reward:1350,instruments:[0],date:new Date().toISOString()}],ledger:[{type:'Carried credits',amount:4200}],mission:null}))`);
  await send('Page.reload'); await sleep(700);
  assert.equal(await ev('campaign.credits'), 4200); assert.equal(await ev('unlockedWorldCount(campaign)'), 2);
  assert.equal(await ev('campaign.version'), 3);
  await ev('confirmReset();document.querySelector("#confirm-reset").click()'); await sleep(750);
  assert.equal(await ev('campaign.credits'), 1000); assert.equal(await ev('selected'), 'Mercury');
  assert.equal(await ev('document.querySelectorAll(".destination-card").length'), 1);
  assert.equal(await ev('document.querySelector("#build").disabled'), false);
  const dimensions = await ev(`{const c=document.querySelector('#destination-planet'),r=c.getBoundingClientRect();({w:c.width,h:c.height,rw:r.width,rh:r.height})}`);
  assert.equal(dimensions.w, dimensions.h); assert.ok(Math.abs(dimensions.rw - dimensions.rh) < 0.1);
  await ev('document.querySelector("#next-world").click()');
  assert.equal(await ev('selected'), 'Venus'); assert.equal(await ev('document.querySelector("#build").disabled'), true);
  await ev('document.querySelector(\'[data-step="1"]\').click()'); assert.equal(await ev('document.querySelector("#modal").open'), true);
  await ev('closeModal();document.querySelector("#previous-world").click()');
